#include <cstdlib>
#include <gtest/gtest.h>
#include <fstream>

/// @file eval_test.cpp
///

/// @addtogroup SBGraphEvalTests
/// @{

class EvalTests : public testing::TestWithParam<const char*> {
};

TEST_P(EvalTests, Eval)
{
  const std::string NAME = GetParam();
  std::cout << "Testing program: " << NAME << std::endl;

  // Tests are executed from build/bin folder generated by cmake.
  const std::string TEST_ROOT = "../..";
  const std::string EVAL_TEST_ROOT = TEST_ROOT + "/eval";

  const std::string TEST_DIR = EVAL_TEST_ROOT + "/test_data/" + NAME;
  const std::string DIR_CMD = "mkdir -p " + TEST_DIR;
  std::system(DIR_CMD.c_str());
  const std::string EVAL_CMD = TEST_ROOT + "/../bin/sbg-eval -f " + TEST_ROOT + "/" + NAME
    + ".test > " + TEST_DIR + "/" + NAME + ".log 2>&1";
  std::system(EVAL_CMD.c_str());
  const std::string TEST_CMD = EVAL_TEST_ROOT + "/results.sh " + NAME + " " + EVAL_TEST_ROOT;
  std::system(TEST_CMD.c_str());

  const std::string RESULT_FILE = EVAL_TEST_ROOT + "/test_data/" + NAME + "/" + NAME + ".passed";
  std::ifstream result(RESULT_FILE.c_str());
  
  const std::string FAILED_RESULT_FILE = EVAL_TEST_ROOT + "/test_data/" + NAME + "/" + NAME + ".log.failed";
  std::ifstream failed_test(FAILED_RESULT_FILE.c_str());
  if (failed_test.good()) {
    const std::string CAT_CMD = "cat " + FAILED_RESULT_FILE;
    std::system(CAT_CMD.c_str());
  }
  EXPECT_TRUE(result.good());
}

const char* eval_program[] = {"arithmetic", "interval", "set", "lexp", "map"
 , "pw_map1", "pw_map2", "pw_map3"};

INSTANTIATE_TEST_SUITE_P(EvalInst, EvalTests, testing::ValuesIn(eval_program));

